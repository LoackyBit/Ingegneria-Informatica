import fs from "fs"
import path from "path"
import { fileURLToPath } from "url"

function findProjectRoot() {
  let curr = path.resolve(process.cwd())
  while (curr !== path.dirname(curr)) {
    if (fs.existsSync(path.join(curr, "quartz.config.ts"))) {
      return curr
    }
    curr = path.dirname(curr)
  }
  return path.resolve("/Users/lorenzo/Documents/Ingegneria-Informatica")
}

const VAULT_APPEARANCE = "/Users/lorenzo/Documents/GitHub/loackyPKM/.obsidian/appearance.json"
const REPO_DIR = findProjectRoot()
const REPO_APPEARANCE = path.join(REPO_DIR, "obsidian-appearance.json")
const SCSS_TARGET = path.join(REPO_DIR, "quartz", "styles", "obsidian-fonts.scss")

export function syncFonts() {
  let appearanceData = {}

  // 1. Leggi dal Vault se disponibile
  if (fs.existsSync(VAULT_APPEARANCE)) {
    try {
      const rawVault = fs.readFileSync(VAULT_APPEARANCE, "utf-8")
      appearanceData = JSON.parse(rawVault)
      // Sincronizza nel repo
      fs.writeFileSync(REPO_APPEARANCE, JSON.stringify(appearanceData, null, 2), "utf-8")
    } catch (err) {
      console.warn("⚠️ Impossibile leggere appearance.json dal vault, fallback su repo:", err.message)
    }
  }

  // 2. Fallback su obsidian-appearance.json se vault non raggiungibile
  if (Object.keys(appearanceData).length === 0 && fs.existsSync(REPO_APPEARANCE)) {
    try {
      appearanceData = JSON.parse(fs.readFileSync(REPO_APPEARANCE, "utf-8"))
    } catch (err) {
      console.warn("⚠️ Impossibile leggere obsidian-appearance.json:", err.message)
    }
  }

  const interfaceFont = appearanceData.interfaceFontFamily || "Arial"
  const textFont = appearanceData.textFontFamily || "NewComputerModern Math"
  const monoFont = appearanceData.monospaceFontFamily
    ? appearanceData.monospaceFontFamily.split(",")[0].trim()
    : "JetBrains Mono"

  const scssContent = `// ==============================================================================
// Auto-generated by sync-fonts.mjs - NON MODIFICARE MANUALMENTE
// Generato automaticamente dalle impostazioni di Obsidian (.obsidian/appearance.json)
// ==============================================================================

// Web Fonts locali per NewComputerModern Math
@font-face {
  font-family: 'NewComputerModern Math';
  src: local('NewComputerModern Math'),
       local('NewComputerModernMath-Regular'),
       url('./static/fonts/NewCMMath-Regular.woff') format('woff'),
       url('./static/fonts/NewCMMath-Regular.otf') format('opentype');
  font-weight: 400;
  font-style: normal;
  font-display: swap;
}

@font-face {
  font-family: 'NewComputerModern Math';
  src: local('NewComputerModernMath-Book'),
       url('./static/fonts/NewCMMath-Book.woff') format('woff'),
       url('./static/fonts/NewCMMath-Book.otf') format('opentype');
  font-weight: 500;
  font-style: normal;
  font-display: swap;
}

@font-face {
  font-family: 'NewComputerModern Math';
  src: local('NewComputerModernMath-Bold'),
       url('./static/fonts/NewCMMath-Bold.woff') format('woff'),
       url('./static/fonts/NewCMMath-Bold.otf') format('opentype');
  font-weight: 700;
  font-style: normal;
  font-display: swap;
}

@font-face {
  font-family: 'NewComputerModern Math';
  src: local('NewComputerModern10-Italic'),
       url('./static/fonts/NewCM10-Italic.woff') format('woff'),
       url('./static/fonts/NewCM10-Italic.otf') format('opentype');
  font-weight: 400;
  font-style: italic;
  font-display: swap;
}

@font-face {
  font-family: 'NewComputerModern Math';
  src: local('NewComputerModern10-BoldItalic'),
       url('./static/fonts/NewCM10-BoldItalic.woff') format('woff'),
       url('./static/fonts/NewCM10-BoldItalic.otf') format('opentype');
  font-weight: 700;
  font-style: italic;
  font-display: swap;
}

:root {
  --obsidian-interface-font: "${interfaceFont}", -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, Helvetica, Arial, sans-serif;
  --obsidian-text-font: "${textFont}", "Computer Modern", Georgia, serif;
  --obsidian-mono-font: "${monoFont}", ui-monospace, SFMono-Regular, "SF Mono", Menlo, Consolas, monospace;

  // Variabili Quartz
  --titleFont: var(--obsidian-interface-font);
  --headerFont: var(--obsidian-interface-font);
  --bodyFont: var(--obsidian-interface-font);
  --codeFont: var(--obsidian-mono-font);
}

// 1. Sito e Navigazione (Interface font da Obsidian: ${interfaceFont})
html,
body,
.page-title,
.search,
.search-button,
.explorer,
.toc,
.graph,
.backlinks,
.breadcrumb-container,
.content-meta,
.tag-link,
footer,
button {
  font-family: var(--obsidian-interface-font);
}

// 2. Testi degli articoli e delle note (Text font da Obsidian: ${textFont})
article,
.popover-inner {
  font-family: var(--obsidian-text-font);

  .article-title,
  h1, h2, h3, h4, h5, h6 {
    font-family: var(--obsidian-text-font);
  }

  p,
  li,
  ol,
  ul,
  blockquote,
  table,
  td,
  th,
  .callout-content,
  figcaption {
    font-family: var(--obsidian-text-font);
  }
}

// 3. Codice (Monospace font da Obsidian: ${monoFont})
code,
pre,
kbd,
samp {
  font-family: var(--obsidian-mono-font) !important;
}
`

  fs.writeFileSync(SCSS_TARGET, scssContent, "utf-8")
  return { interfaceFont, textFont, monoFont }
}

if (process.argv[1] && process.argv[1].endsWith("sync-fonts.mjs")) {
  const fonts = syncFonts()
  console.log(`✅ Font sincronizzati da Obsidian:`)
  console.log(`   - Sito & Navigazione : ${fonts.interfaceFont}`)
  console.log(`   - Testi             : ${fonts.textFont}`)
  console.log(`   - Monospace (Code)  : ${fonts.monoFont}`)
}
